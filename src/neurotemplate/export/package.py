"""
The package every export writes into, and what the exports share.

    <out>/
      README.md            what the package is, what to install, how to run it
      runtime.py           the Python runner (export/runtime.py, verbatim)
      example.py           the smallest useful program
      validate.py          reproduces reference/; only when something is verified
      model/               a dynamics model: warm_start and step graphs,
                           model.json, reference/   (`nt export model`)
      policy/              a control policy: the policy graph, policy.json,
                           reference/               (`nt export policy`)

A package holds graphs in one format (`GRAPH_SUFFIX`): ONNX, run by
onnxruntime; torch programs, run by torch; or C, generated by onnx2c. The
format decides what the package needs installed, so a model and a policy in
one package share it. A C package adds its C runner (export/c/: the drivers,
example.c and validate.c), each artifact's generated header, and a Makefile
that also builds the library runtime.py loads.

A model exported unverified has no reference/; a package with nothing to
check ships no validate. The package never installs or downloads anything:
the README says what it needs.

An export builds its artifact directory in a staging directory, and installs
it only once the staged package passes its own reference check — so a failed
export leaves `<out>` untouched. Installing replaces that one artifact
directory and regenerates every file around the artifacts; the other
artifact, and anything else the project keeps there, are left alone.
"""

from __future__ import annotations

import json
import platform
import shutil
import tempfile
from datetime import datetime, timezone
from importlib import metadata
from pathlib import Path
from string import Template

import onnx
import onnxruntime
import torch

from neurotemplate.export import ccode, runtime
from neurotemplate.export.spec import FORMAT
from neurotemplate.export.trace import OPSET, export_graph, export_program

TEMPLATES = Path(__file__).parent / "templates"

#: Written into every shipped CSV. `%.6f` does not round-trip float32 (it
#: keeps 83 of 1000 normalised-state values and 493 of 1000 kW values exact);
#: `%.9g` round-trips all of them, so the file format never sets the
#: tolerance floor.
FLOAT_FORMAT = "%.9g"

#: The graph formats an export writes, and each one's file suffix.
GRAPH_SUFFIX = {"onnx": ".onnx", "torch": ".pt2", "c": ".c"}

#: Every file an export writes around the artifact directories. Each export
#: rewrites the ones this package needs and removes the rest.
GENERATED = ("README.md", "runtime.py", "example.py", "validate.py", "Makefile",
             "nt_model.c", "nt_model.h", "nt_policy.c", "nt_policy.h",
             "example.c", "validate.c")

#: The torch that saves a package's programs; they load in it or a newer one.
TORCH = torch.__version__.split("+")[0]

#: How the package README describes each format, and what it needs.
FORMAT_TEXT = {
    "onnx": {
        "what": "the trained graphs as ONNX, and `runtime.py`, a small Python "
                "runner for them",
        "install": "```bash\npip install numpy onnxruntime\n```",
    },
    "torch": {
        "what": "the trained graphs as torch programs (`.pt2`), and `runtime.py`, "
                "a small Python runner for them",
        "install": f"```bash\npip install numpy 'torch>={TORCH}'\n```\n\n"
                   "A torch program loads in the torch that saved it or a newer one. "
                   "On Linux, a plain "
                   "`pip install torch` pulls the CUDA build, several GB. For CPU "
                   "only, add `--index-url https://download.pytorch.org/whl/cpu`.",
    },
    "c": {
        "what": "the trained graphs as C, generated by onnx2c; a C runner with no "
                "heap and no I/O; and `runtime.py`, a Python runner over the "
                "compiled C",
        "install": "A C compiler and `make`. The Python runner also needs numpy "
                   "(`pip install numpy`).",
    },
}


def check_graph_format(graph_format: str, exporter: str, onnx2c: str) -> None:
    if graph_format not in GRAPH_SUFFIX:
        raise ValueError(f"unknown graph format {graph_format!r}; expected one "
                         f"of {list(GRAPH_SUFFIX)}.")
    if graph_format == "torch" and exporter != "dynamo":
        raise ValueError("a torch program is captured by torch.export; the "
                         f"{exporter!r} exporter writes ONNX only.")
    if graph_format == "c":
        ccode.check_tools(onnx2c)


def write_graph(graph: torch.nn.Module, args: tuple[torch.Tensor, ...],
                input_names: list[str], output_names: list[str], stem: Path,
                graph_format: str, exporter: str, export_id: str, run_id: str,
                onnx2c: str) -> None:
    """Save `graph`, traced on `args`, as `<stem>.onnx`, `.pt2` or `.c`.

    ONNX and torch files are stamped with the export they belong to, which
    the runtime checks against the json beside them on load; C carries the
    stamp in the artifact's generated header instead.
    """
    path = stem.with_suffix(GRAPH_SUFFIX[graph_format])
    if graph_format == "onnx":
        proto = export_graph(graph, args, input_names, output_names, path, exporter)
        onnx.helper.set_model_props(proto, {
            "export_id": export_id, "opset": str(OPSET), "run_id": run_id,
        })
        onnx.save(proto, str(path))
    elif graph_format == "torch":
        program = export_program(graph, args, input_names)
        torch.export.save(program, str(path), extra_files={
            runtime.STAMP: json.dumps({"export_id": export_id, "run_id": run_id}),
        })
    else:
        with tempfile.TemporaryDirectory() as tmp:
            traced = Path(tmp) / f"{stem.name}.onnx"
            export_graph(graph, args, input_names, output_names, traced, exporter)
            ccode.generate(traced, path, f"nt_{stem.name}_graph", onnx2c)


def provenance(graph_format: str, exporter: str) -> dict:
    """Where and with what a reference was produced, for REFERENCE.json."""
    return {
        "graph_format": graph_format,
        "created": datetime.now(timezone.utc).isoformat(timespec="seconds"),
        "platform": platform.platform(),
        "python": platform.python_version(),
        "neurotemplate": metadata.version("neurotemplate"),
        "torch": torch.__version__,
        "onnx": onnx.__version__,
        "onnxruntime": onnxruntime.__version__,
        "exporter": exporter,
    }


def write_json(path: Path, document: dict) -> None:
    path.write_text(json.dumps(document, indent=2) + "\n", encoding="utf-8")


def install(stage: Path, out_dir: Path, artifact: str) -> None:
    """Check the staged `artifact` directory, then move it into `out_dir`."""
    failed = [check for check in runtime.check_reference(stage) if not check.ok]
    if failed:
        raise RuntimeError("REFUSING TO WRITE: the staged package fails its own "
                           "reference check:\n" + "\n".join(c.report() for c in failed))
    _check_neighbour(stage, out_dir, artifact)

    out_dir.mkdir(parents=True, exist_ok=True)
    shutil.rmtree(out_dir / artifact, ignore_errors=True)
    shutil.copytree(stage / artifact, out_dir / artifact)
    _write_package_files(out_dir)


def _check_neighbour(stage: Path, out_dir: Path, artifact: str) -> None:
    """Refuse to install beside an artifact the regenerated runtime cannot run:
    one in another graph format, or written by an older export."""
    other = "policy" if artifact == "model" else "model"
    path = out_dir / other / f"{other}.json"
    if not path.exists():
        return
    theirs = json.loads(path.read_text(encoding="utf-8"))
    graph_format = _read_spec(stage, artifact)["graph_format"]
    if (theirs["format"], theirs.get("graph_format")) != (FORMAT, graph_format):
        raise RuntimeError(
            f"REFUSING TO WRITE: {out_dir / other} was not exported as "
            f"{graph_format} in json format {FORMAT}, and a package has one runtime. "
            f"Re-export {other} the same way, or write this {artifact} to "
            "another --out.")


def _read_spec(root: Path, artifact: str) -> dict:
    return json.loads((root / artifact / f"{artifact}.json").read_text(encoding="utf-8"))


def _render(name: str, **values: str) -> str:
    return Template((TEMPLATES / name).read_text(encoding="utf-8")).substitute(values)


def _write_package_files(out_dir: Path) -> None:
    """Everything around the artifact directories, from what `out_dir` holds."""
    specs = {name: _read_spec(out_dir, name)
             for name in ("model", "policy") if (out_dir / name).is_dir()}
    # One format per package (`_check_neighbour`), so any spec says which.
    graph_format = next(iter(specs.values()))["graph_format"]
    verified = [name for name in specs if (out_dir / name / "reference").is_dir()]
    files: dict[str, str] = {
        "runtime.py": Path(runtime.__file__).read_text(encoding="utf-8"),
        "example.py": _render("example.py.tmpl"),
        "README.md": _readme(specs, graph_format, verified),
    }
    if verified:
        files["validate.py"] = _render("validate.py.tmpl")
    if graph_format == "c":
        files.update(_c_files(specs, verified))

    for name in GENERATED:
        if name in files:
            (out_dir / name).write_text(files[name], encoding="utf-8")
        else:
            (out_dir / name).unlink(missing_ok=True)


def _c_files(specs: dict, verified: list[str]) -> dict[str, str]:
    """The C runner, and the Makefile that builds it for these artifacts."""
    shipped = ["example.c"] + (["validate.c"] if verified else [])
    sources, defines = [], []
    for name in specs:
        shipped += [f"nt_{name}.c", f"nt_{name}.h"]
        graphs = ["warm_start", "step"] if name == "model" else ["policy"]
        sources += [f"nt_{name}.c"] + [f"{name}/{graph}.c" for graph in graphs]
        defines.append(f"-DNT_HAVE_{name.upper()}")
    programs = ["example"] + (["validate"] if verified else [])
    then = [f"./{p}" for p in programs] + [f"python {p}.py" for p in programs]
    files = {name: (ccode.SOURCES / name).read_text(encoding="utf-8") for name in shipped}
    files["Makefile"] = _render("Makefile.tmpl", sources=" ".join(sources),
                                defines=" ".join(defines), programs=" ".join(programs),
                                then=", ".join(then))
    return files


def _readme(specs: dict, graph_format: str, verified: list[str]) -> str:
    title = next((s["description"] for s in specs.values() if s["description"]),
                 "NeuroTemplate export")
    run = ["make"] if graph_format == "c" else []
    for program in (["validate"] if verified else []) + ["example"]:
        if graph_format == "c":
            run.append(f"./{program}")
        run.append(f"python {program}.py")
    shapes = ("The batch is fixed at 1, and every other shape is a compile-time "
              "constant in the generated headers." if graph_format == "c" else
              "Only the batch axis of a window may vary; a window of the wrong "
              "length or width is rejected, naming the dimension.")

    sections = []
    if "model" in specs:
        model = specs["model"]
        sections.append(_render("README_model.md.tmpl", contract=_model_contract(model),
                                history_steps=str(model["history_steps"]),
                                timestep_seconds=f"{model['timestep_seconds']:g}",
                                state_width=str(model["state"]["width"])))
    if "policy" in specs:
        sections.append(_render("README_policy.md.tmpl",
                                contract=_policy_contract(specs["policy"])))
    if graph_format in ("torch", "c"):
        sections.append(_render(f"README_{graph_format}.md.tmpl"))
    if verified:
        sections.append(_render("README_validate.md.tmpl"))
    return _render("README.md.tmpl", title=title, shapes=shapes,
                   what=FORMAT_TEXT[graph_format]["what"],
                   install=FORMAT_TEXT[graph_format]["install"],
                   run="\n".join(run), sections="\n\n".join(s.strip() for s in sections))


def _model_contract(spec: dict) -> str:
    rows = ["| role | column | unit |", "|---|---|---|"]
    for role, key in (("output (y)", "y_columns"), ("control (u)", "u_columns"),
                      ("disturbance (d)", "d_columns")):
        for column in spec[key]:
            rows.append(f"| {role} | `{column}` | {spec['units'][column] or '—'} |")
    return "\n".join(rows)


def _policy_contract(spec: dict) -> str:
    rows = ["| input | steps | current row | columns |", "|---|---|---|---|"]
    for name, entry in spec["inputs"].items():
        columns = ", ".join(f"`{c}`" for c in entry["columns"])
        rows.append(f"| `{name}` | {entry['steps']} | {entry['current_row']} | {columns} |")
    rows.append(f"| **output** `command` | | | {', '.join(f'`{c}`' for c in spec['u_columns'])} |")
    return "\n".join(rows)
